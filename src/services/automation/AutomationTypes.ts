/**
 * J.A.R.V.I.S. Automation Subsystem
 * Architecture Contract & Type Definitions
 * 
 * Separated from UI layers to facilitate native Android Accessibility Service integration.
 */

export type ExecutionEnvironment = 'browser_web' | 'android_webview' | 'android_native_service';

export type TriggerSource = 
  | 'ACCESSIBILITY_EVENT'      // Generated by Android AccessibilityService (e.g. TYPE_WINDOW_STATE_CHANGED)
  | 'VOICE_COMMAND'            // Spoken keyword in PT-BR
  | 'BATTERY_TELEMETRY'        // Hardware battery status change
  | 'SCHEDULED_ALARM'          // AlarmManager / cron timer
  | 'BROADCAST_INTENT';        // Android OS Broadcasts (e.g. SCREEN_ON, BOOT_COMPLETED)

export type ActionTarget = 
  | 'ACCESSIBILITY_INTERACTION' // Toque em view ID, clique em texto, leitura de tela
  | 'INTERNAL_SYNTHESIS'       // TTS speech, audio chime, navegação interna
  | 'SYSTEM_GLOBAL_ACTION'     // Voltar, Início, Recentes, Barra de Notificações
  | 'EXTERNAL_INTENT';         // Disparo de Intent para outro aplicativo Android

export interface AutomationTrigger {
  source: TriggerSource;
  filter: {
    packageName?: string;         // Ex: "com.whatsapp", "com.android.settings"
    viewId?: string;              // Ex: "com.example.app:id/submit_button"
    keywordPattern?: string;      // Ex: "iniciar protocolo"
    batteryPercentThreshold?: number;
    cronExpression?: string;
    intentAction?: string;
  };
}

export interface AutomationAction {
  target: ActionTarget;
  payload: {
    clickByViewId?: string;
    clickByText?: string;
    scrollDirection?: 'up' | 'down';
    globalActionCode?: 1 | 2 | 3 | 4; // 1 = GLOBAL_ACTION_BACK, 2 = GLOBAL_ACTION_HOME, 3 = GLOBAL_ACTION_RECENTS, 4 = GLOBAL_ACTION_NOTIFICATIONS
    ttsPrompt?: string;
    internalActionId?: string;
  };
}

export interface AutomationDefinition {
  id: string;
  name: string;
  description: string;
  trigger: AutomationTrigger;
  action: AutomationAction;
  enabled: boolean;
  requiresAccessibilityService: boolean;
  minAndroidSdk: number; // Ex: 26 (Android 8.0) or 31 (Android 12)
  createdAt: number;
}

export interface ExecutionResult {
  automationId: string;
  success: boolean;
  dispatchedAt: number;
  environment: ExecutionEnvironment;
  statusMessage: string;
  nativeCode?: number;
}
